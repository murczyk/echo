import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const tokensPath = fileURLToPath(new URL('../src/design-system/tokens.json', import.meta.url));
const outputPath = fileURLToPath(
  new URL('../src/styles/_design-tokens.generated.css', import.meta.url),
);

const toKebabCase = (value) => value.replaceAll(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

function renderCustomProperties(namespace, tokens) {
  return Object.entries(tokens)
    .map(([name, value]) => `  --echo-${namespace}-${toKebabCase(name)}: ${value};`)
    .join('\n');
}

function renderTailwindProperties(namespace, tokens, valueFor) {
  return Object.entries(tokens)
    .map(([name, value]) => `  --${namespace}-echo-${toKebabCase(name)}: ${valueFor(name, value)};`)
    .join('\n');
}

function renderCss(tokens) {
  const breakpoints = renderTailwindProperties(
    'breakpoint',
    tokens.breakpoint,
    (_, value) => value,
  );
  const colors = renderTailwindProperties(
    'color',
    tokens.colorReference,
    (name) => `var(--echo-color-${toKebabCase(name)})`,
  );
  const spacing = renderTailwindProperties(
    'spacing',
    tokens.spacing,
    (name) => `var(--echo-spacing-${toKebabCase(name)})`,
  );
  const sizes = renderTailwindProperties(
    'spacing',
    tokens.size,
    (name) => `var(--echo-size-${toKebabCase(name)})`,
  );
  const radii = renderTailwindProperties(
    'radius',
    tokens.radius,
    (name) => `var(--echo-radius-${toKebabCase(name)})`,
  );
  const fontSizes = renderTailwindProperties(
    'text',
    tokens.fontSize,
    (name) => `var(--echo-font-size-${toKebabCase(name)})`,
  );
  const shadows = renderTailwindProperties(
    'shadow',
    tokens.shadow,
    (name) => `var(--echo-shadow-${toKebabCase(name)})`,
  );
  const colorReferences = Object.entries(tokens.colorReference)
    .map(([name, reference]) => `  --echo-color-${toKebabCase(name)}: var(${reference});`)
    .join('\n');

  return `/* Generated by scripts/design-tokens.mjs. Do not edit directly. */

@theme {
${breakpoints}
}

@theme inline {
${colors}
${spacing}
${sizes}
${radii}
${fontSizes}
${shadows}
}

:root {
${renderCustomProperties('spacing', tokens.spacing)}
${renderCustomProperties('size', tokens.size)}
${renderCustomProperties('radius', tokens.radius)}
${renderCustomProperties('font-size', tokens.fontSize)}
${renderCustomProperties('breakpoint', tokens.breakpoint)}
${renderCustomProperties('shadow', tokens.shadow)}
${colorReferences}
}
`;
}

const tokens = JSON.parse(await readFile(tokensPath, 'utf8'));
const expectedCss = renderCss(tokens);

if (process.argv.includes('--check')) {
  const actualCss = await readFile(outputPath, 'utf8').catch(() => '');

  if (actualCss !== expectedCss) {
    console.error('Design tokens are stale. Run `npm run tokens:generate`.');
    process.exitCode = 1;
  }
} else {
  await writeFile(outputPath, expectedCss);
}
