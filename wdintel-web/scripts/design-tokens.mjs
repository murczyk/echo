import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const tokensPath = fileURLToPath(new URL('../src/design-system/tokens.json', import.meta.url));
const cssOutputPath = fileURLToPath(
  new URL('../src/styles/_design-tokens.generated.css', import.meta.url),
);
const typeScriptOutputPath = fileURLToPath(
  new URL('../src/design-system/design-tokens.ts', import.meta.url),
);
const requiredGroups = ['color', 'spacing', 'size', 'radius', 'typography', 'breakpoint', 'shadow'];
const requiredColors = [
  'background',
  'surface',
  'surfaceRaised',
  'surfaceInactive',
  'text',
  'textMuted',
  'textDisabled',
  'border',
  'divider',
  'primary',
  'primaryHover',
  'primaryActive',
  'onPrimary',
  'secondary',
  'success',
  'warning',
  'error',
  'info',
  'focus',
  'hover',
  'active',
  'selected',
  'disabled',
  'disabledBackground',
];
const dimensionPattern = /^(?:0|[1-9]\d*)(?:\.\d+)?(?:px|rem|em|%|vh|vw)$/;
const colorPattern = /^#[0-9a-f]{6}$/i;
const toKebabCase = (value) => value.replaceAll(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

function assertObject(value, path) {
  if (!value || typeof value !== 'object' || Array.isArray(value))
    throw new Error(`${path} must be an object.`);
}

function assertExactKeys(value, keys, path) {
  assertObject(value, path);
  const actual = Object.keys(value);
  const missing = keys.filter((key) => !actual.includes(key));
  const unknown = actual.filter((key) => !keys.includes(key));
  if (missing.length || unknown.length)
    throw new Error(
      `${path} has invalid keys (missing: ${missing.join(', ') || 'none'}; unknown: ${unknown.join(', ') || 'none'}).`,
    );
}

function assertDimensions(value, path) {
  assertObject(value, path);
  for (const [name, dimension] of Object.entries(value)) {
    if (typeof dimension !== 'string' || !dimensionPattern.test(dimension))
      throw new Error(`${path}.${name} must be a CSS dimension.`);
  }
}

function validateTokens(tokens) {
  assertExactKeys(tokens, requiredGroups, 'tokens');
  assertExactKeys(tokens.color, ['light', 'dark'], 'tokens.color');
  for (const mode of ['light', 'dark']) {
    assertExactKeys(tokens.color[mode], requiredColors, `tokens.color.${mode}`);
    for (const [name, color] of Object.entries(tokens.color[mode])) {
      if (typeof color !== 'string' || !colorPattern.test(color))
        throw new Error(`tokens.color.${mode}.${name} must be a six-digit hexadecimal color.`);
    }
  }
  assertDimensions(tokens.spacing, 'tokens.spacing');
  assertDimensions(tokens.size, 'tokens.size');
  assertDimensions(tokens.radius, 'tokens.radius');
  assertDimensions(tokens.breakpoint, 'tokens.breakpoint');
  assertExactKeys(tokens.typography, ['fontFamily', 'fontSize'], 'tokens.typography');
  if (typeof tokens.typography.fontFamily !== 'string' || !tokens.typography.fontFamily)
    throw new Error('tokens.typography.fontFamily must be a non-empty string.');
  assertDimensions(tokens.typography.fontSize, 'tokens.typography.fontSize');
  assertObject(tokens.shadow, 'tokens.shadow');
  for (const [name, shadow] of Object.entries(tokens.shadow)) {
    if (typeof shadow !== 'string' || !shadow)
      throw new Error(`tokens.shadow.${name} must be a string.`);
  }
}

function renderCustomProperties(namespace, entries) {
  return Object.entries(entries)
    .map(([name, value]) => `  --echo-${namespace}-${toKebabCase(name)}: ${value};`)
    .join('\n');
}

function renderTailwindProperties(
  namespace,
  entries,
  valueFor = (name) => `var(--echo-${namespace}-${toKebabCase(name)})`,
) {
  return Object.keys(entries)
    .map((name) => `  --${namespace}-echo-${toKebabCase(name)}: ${valueFor(name)};`)
    .join('\n');
}

function renderCss(tokens) {
  return `/* Generated by scripts/design-tokens.mjs. Do not edit directly. */

@theme {
${renderTailwindProperties('breakpoint', tokens.breakpoint, (name) => tokens.breakpoint[name])}
}

@theme inline {
${renderTailwindProperties('color', tokens.color.light)}
${renderTailwindProperties('spacing', tokens.spacing)}
${renderTailwindProperties('spacing', tokens.size, (name) => `var(--echo-size-${toKebabCase(name)})`)}
${renderTailwindProperties('radius', tokens.radius)}
${renderTailwindProperties('text', tokens.typography.fontSize, (name) => `var(--echo-typography-font-size-${toKebabCase(name)})`)}
${renderTailwindProperties('shadow', tokens.shadow)}
}

:root {
${renderCustomProperties('color', tokens.color.light)}
${renderCustomProperties('spacing', tokens.spacing)}
${renderCustomProperties('size', tokens.size)}
${renderCustomProperties('radius', tokens.radius)}
  --echo-typography-font-family: ${tokens.typography.fontFamily};
${renderCustomProperties('typography-font-size', tokens.typography.fontSize)}
${renderCustomProperties('breakpoint', tokens.breakpoint)}
${renderCustomProperties('shadow', tokens.shadow)}
}

html[data-bs-theme='dark'] {
${renderCustomProperties('color', tokens.color.dark)}
}
`;
}

function renderTypeScript(tokens) {
  return `// Generated by scripts/design-tokens.mjs. Do not edit directly.\n\nexport const designTokens = ${JSON.stringify(tokens, null, 2)} as const;\n\nexport type DesignTokens = typeof designTokens;\nexport type EchoColorName = keyof DesignTokens['color']['light'];\nexport type EchoColorMode = keyof DesignTokens['color'];\n`;
}

async function main() {
  const tokens = JSON.parse(await readFile(tokensPath, 'utf8'));
  validateTokens(tokens);
  const outputs = [
    [cssOutputPath, renderCss(tokens)],
    [typeScriptOutputPath, renderTypeScript(tokens)],
  ];
  if (process.argv.includes('--check')) {
    const stale = await Promise.all(
      outputs.map(
        async ([outputPath, expected]) =>
          (await readFile(outputPath, 'utf8').catch(() => '')) !== expected,
      ),
    );
    if (stale.some(Boolean)) {
      console.error('Design tokens are stale. Run `npm run tokens:generate`.');
      process.exitCode = 1;
    }
    return;
  }
  await Promise.all(outputs.map(([outputPath, content]) => writeFile(outputPath, content)));
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
